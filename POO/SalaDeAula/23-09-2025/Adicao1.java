public class Adicao1 {

    public int addInt(int a, int b)
    {
        return a + b;
    }

    public float addFloat(float c, float d)
    {
        return c + d;
    }

    public String exibeInt(int a, int b, int resultado)
    {
        return "Adição de inteiros: " + a + " + " + b + " + " + " = " + resultado;
    }

    public String exibeFloat(float c, float d, float resultado)
    {
        return "Adição de floats: " + c + " + " + d + " = " + resultado;
    }
}